#!/usr/bin/env python3
"""Generate kexpad.inf from the Linux xpad driver's device table.

usage: gen_inf.py path/to/drivers/input/joystick/xpad.c > kexpad.inf

Every { vid, pid, "name", flags, XTYPE_XBOX360 } entry becomes a hardware
ID, both as a whole device (USB\\VID_v&PID_p) and as interface 0 of a
composite device (USB\\VID_v&PID_p&MI_00): Windows 98 SE creates the second
form when the device class is 0 and the hub driver splits interfaces.
Devices not in the list still match the compatible ID of the Xbox 360 game
pad interface, vendor class FF, subclass 5D, protocol 01.

Xbox 360 wireless receivers (XTYPE_XBOX360W) speak a different protocol and
are not included yet.
"""
import re
import sys

ENTRY = re.compile(r'\{\s*0x([0-9a-fA-F]{4}),\s*0x([0-9a-fA-F]{4}),\s*"([^"]*)",\s*[^,]*,\s*XTYPE_XBOX360\s*\}')

# controllers KernelExEx names even if a future xpad drops them
EXTRA = [
    ("2dc8", "310a", "8BitDo Ultimate 2C Wireless Controller"),
    ("2dc8", "3106", "8BitDo Ultimate Wired Controller"),
]


def inf_string(s):
    s = s.strip().replace('"', "'")
    return "".join(c for c in s if 32 <= ord(c) < 127)


def main():
    src = open(sys.argv[1], encoding="utf-8", errors="replace").read()
    seen, devs = set(), []
    for vid, pid, name in [(m.group(1), m.group(2), m.group(3)) for m in ENTRY.finditer(src)] + EXTRA:
        key = (vid.lower(), pid.lower())
        if key in seen:
            continue
        seen.add(key)
        devs.append((key[0].upper(), key[1].upper(), inf_string(name) or "Xbox 360 compatible controller"))

    out = []
    w = out.append
    w("; kexpad.inf - KernelExEx driver for Xbox 360-protocol USB controllers")
    w("; Windows 98 SE / ME. Generated by input/kexpad/gen_inf.py from the Linux")
    w("; xpad device table; edit the generator, not this file.")
    w(";")
    w("; hidclass.sys and hidparse.sys are Microsoft's and come from the Windows")
    w("; CD (layout.inf), as for any USB HID device.")
    w("")
    w("[Version]")
    w('Signature="$CHICAGO$"')
    w("Class=HID")
    w("ClassGUID={745a17a0-74d3-11d0-b6fe-00a0c90f57da}")
    w("Provider=%KernelExEx%")
    w("LayoutFile=layout.inf")
    w("DriverVer=11/10/2026,4.7.0.0")
    w("")
    w("[SourceDisksNames]")
    w('99="KernelExEx",,0')
    w("")
    w("[SourceDisksFiles]")
    w("kexpad.sys=99")
    w("")
    w("[DestinationDirs]")
    w("DefaultDestDir=10,system32\\drivers")
    w("KexPad.Copy=10,system32\\drivers")
    w("KexPad.HidCopy=10,system32\\drivers")
    w("")
    w("[Manufacturer]")
    w("%KernelExEx%=KexPad.Devices")
    w("")
    w("[KexPad.Devices]")
    w("%Generic%=KexPad.Install,USB\\Class_FF&SubClass_5D&Prot_01")
    for i, (vid, pid, _) in enumerate(devs):
        w(f"%Dev{i}%=KexPad.Install,USB\\VID_{vid}&PID_{pid}")
        w(f"%Dev{i}%=KexPad.Install,USB\\VID_{vid}&PID_{pid}&MI_00")
    w("")
    w("[KexPad.Install]")
    w("CopyFiles=KexPad.Copy,KexPad.HidCopy")
    w("AddReg=KexPad.AddReg")
    w("")
    w("[KexPad.Copy]")
    w("kexpad.sys")
    w("")
    w("[KexPad.HidCopy]")
    w("hidclass.sys")
    w("hidparse.sys")
    w("")
    w("[KexPad.AddReg]")
    w("HKR,,DevLoader,,*ntkern")
    w('HKR,,NTMPDriver,,"kexpad.sys"')
    w("")
    w("[Strings]")
    w('KernelExEx="KernelExEx"')
    w('Generic="Xbox 360 compatible controller (KernelExEx)"')
    for i, (_, _, name) in enumerate(devs):
        w(f'Dev{i}="{name}"')
    sys.stdout.write("\r\n".join(out) + "\r\n")
    print(f"{len(devs)} devices", file=sys.stderr)


if __name__ == "__main__":
    main()
