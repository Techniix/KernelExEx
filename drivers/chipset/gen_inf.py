#!/usr/bin/env python3
"""Generate the KernelExEx chipset INFs from pci.ids (GPLv2-or-BSD-3, pciutils):
names for the parts of Intel chipsets newer than Windows 98 SE knows
(ICH2 to ICH10, 845 to X48/P45 hosts), installed the way 98 SE installs the
same functions of the first ICH (machine.inf, mshdc.inf, usb.inf):

  kexchip.inf  System: LPC (ISA bus), SMBus, PCI/AGP/PCIe bridges, host bridges
  kexide.inf   hdc:    IDE and SATA (IDE mode) controllers
  kexuhci.inf  USB:    UHCI controllers (Windows 98's own uhcd.sys)

usage: gen_inf.py PCI_IDS OUTDIR   (also writes kexchip_ids.nsh for setup)
"""
import re
import sys
from pathlib import Path

# device ID ranges of the chipsets we cover (ICH2..ICH7, 6300ESB, ICH8 PATA, and their hosts)
RANGES = [(0x2440, 0x245F), (0x2480, 0x248F), (0x24C0, 0x24DF), (0x25A0, 0x25AF), (0x2640, 0x266F),
          (0x27B0, 0x27DF), (0x2850, 0x2850), (0x1A30, 0x1A31), (0x2530, 0x2533), (0x2560, 0x2563),
          (0x2570, 0x2573), (0x2578, 0x257B), (0x2580, 0x2591), (0x2770, 0x2777), (0x277C, 0x277D),
          (0x3340, 0x3341), (0x3580, 0x3584), (0x2588, 0x2589), (0x25D0, 0x25FF), (0x3590, 0x359F),
          # ICH8, ICH9, ICH10 and the G31/G33/P35/G41/G45/P45/X38/X48 hosts
          (0x2810, 0x285F), (0x2910, 0x294F), (0x3A00, 0x3A7F), (0x29B0, 0x29B1), (0x29C0, 0x29C1), (0x29D0, 0x29D1),
          (0x29E0, 0x29E1), (0x29F0, 0x29F1), (0x2E00, 0x2E33), (0x2A00, 0x2A01), (0x2A40, 0x2A41)]
# SATA in RAID-only mode (RAID class, not IDE): not ours
RAID_ONLY = {0x24DF, 0x2652, 0x2653}
# 98 SE knows these already (82801AA/AB)
KNOWN = {0x2410, 0x2411, 0x2412, 0x2413, 0x2418, 0x2420, 0x2421, 0x2422, 0x2423, 0x2428}


def classify(name):
    n = name.lower()
    if "lpc" in n or "isa bridge" in n:
        return "chip", "ISA_DRV"
    if "smbus" in n:
        return "chip", "NO_DRV"
    if "ehci" in n or "usb2" in n or "usb 2" in n:
        return None, None   # USB 2.0: KernelExEx's own EHCI driver, later
    if "uhci" in n or "universal host" in n or ("usb" in n and "1.1" in n) or "usb controller #" in n:
        return "uhci", "UHCI"
    if n.endswith("sata controller"):   # ICH5 24D1, ICH6 2651/2653: IDE-compatible SATA
        return "ide", "DUAL_GOOD_IDE"
    if ("ide" in n or "ultra ata" in n or "pata" in n or ("sata" in n and "ide" in n)
            or ("serial ata" in n and "raid" not in n and "ahci" not in n)) and "raid" not in n and "ahci" not in n:
        return "ide", "DUAL_GOOD_IDE"
    if "agp" in n or "pci bridge" in n or "pci express root port" in n or "hub interface to pci" in n \
            or "pci-to-pci" in n or "pci express port" in n:
        return "chip", "PCI_BRIDGE_DRV"
    if "memory controller hub" in n or "dram controller" in n or "host bridge" in n or "host-hub" in n \
            or "processor to i/o" in n or "host controller" in n and "usb" not in n:
        return "chip", "NO_DRV"
    return None, None


def read(ids):
    out = []
    vendor = None
    for line in Path(ids).read_text(encoding="utf-8", errors="replace").splitlines():
        if not line or line.startswith("#"):
            continue
        m = re.match(r"^([0-9a-f]{4})\s+(.*)", line)
        if m:
            vendor = int(m.group(1), 16)
            continue
        m = re.match(r"^\t([0-9a-f]{4})\s+(.*)", line)
        if m and vendor == 0x8086:
            out.append((int(m.group(1), 16), m.group(2).strip()))
    return out


def main():
    ids, outdir = sys.argv[1], Path(sys.argv[2])
    devs = {"chip": [], "ide": [], "uhci": []}
    for dev, name in read(ids):
        if dev in KNOWN or dev in RAID_ONLY or not any(a <= dev <= b for a, b in RANGES):
            continue
        kind, sect = classify(name)
        if kind:
            devs[kind].append((dev, sect, "Intel " + name))
    head = ["; {file} - KernelExEx chipset support for Windows 98 SE / ME: {what}",
            "; Generated by drivers/chipset/gen_inf.py from pci.ids (pciutils, GPLv2 or BSD-3). Do not edit.",
            "; Installs each device the way Windows 98 SE installs the same function of the",
            "; first Intel ICH (machine.inf, mshdc.inf, usb.inf); it only names devices and",
            "; loads Windows' own drivers.", ""]
    common_tail = ["[Strings]", 'KEX="KernelExEx"', 'INTEL="Intel"']
    files = {
        "kexchip.inf": ("System", "{4d36e97d-e325-11ce-bfc1-08002be10318}", "LPC, SMBus, bridges and host bridges", "chip"),
        "kexide.inf": ("hdc", "{4d36e96a-e325-11ce-bfc1-08002be10318}", "IDE and SATA (IDE mode) controllers", "ide"),
        "kexuhci.inf": ("USB", "{36FC9E60-C465-11CF-8056-444553540000}", "USB 1.1 (UHCI) controllers", "uhci"),
    }
    sections = {
        "ISA_DRV": ["AddReg=KEX_ISA.AddReg,KEX_SysProp.AddReg"],
        "NO_DRV": ["DelReg=KEX_RemoveDevLoader"],
        "PCI_BRIDGE_DRV": ["AddReg=KEX_SysProp.AddReg"],
        "DUAL_GOOD_IDE": ["AddReg=KEX_PCIMF.Reg,KEX_IDEProp.Reg"],
        "UHCI": ["AddReg=KEX_UHCI.AddReg,KEX_USB.AddReg", "CopyFiles=KEX_UHCI.CopyFiles,KEX_USB.CopyFiles,KEX_USBUI.CopyFiles"],
    }
    regs = {
        "chip": ["[KEX_ISA.AddReg]", "HKR,,DevLoader,,isapnp.vxd", "",
                 "[KEX_SysProp.AddReg]", 'HKR,,EnumPropPages,,"sysclass.dll,EnumPropPages"', "",
                 "[KEX_RemoveDevLoader]", "HKR,,DevLoader", ""],
        "ide": ["[KEX_PCIMF.Reg]", "HKR,,DevLoader,,*CONFIGMG", "HKR,,Enumerator,,*CONFIGMG",
                "HKR,,CMDrivFlags,1,03,00,00,00", "", "[KEX_IDEProp.Reg]",
                'HKR,,EnumPropPages,,"sysclass.dll,IDEEnumPropPages"', ""],
        "uhci": ["[KEX_UHCI.AddReg]", "HKR,,NTMPDriver,,uhcd.sys",
                 'HKR,,EnumPropPages,,"sysclass.dll,USBControllerPropPage"', "",
                 "[KEX_USB.AddReg]", "HKR,,DevLoader,,*NTKERN", "",
                 "[KEX_UHCI.CopyFiles]", "uhcd.sys", "", "[KEX_USB.CopyFiles]", "usbd.sys", "usbhub.sys", "",
                 "[KEX_USBUI.CopyFiles]", "usbui.dll", "",
                 "[DestinationDirs]", "KEX_USBUI.CopyFiles=11", "DefaultDestDir=10,system32\\drivers", ""],
    }
    for fname, (cls, guid, what, kind) in files.items():
        L = [h.format(file=fname, what=what) for h in head]
        L += ["[Version]", 'Signature="$CHICAGO$"', "LayoutFile=Layout.inf, Layout1.inf, Layout2.inf", f"Class={cls}",
              f"ClassGUID={guid}", "Provider=%KEX%", "", "[Manufacturer]", "%INTEL%=Intel", "", "[Intel]"]
        used = sorted({d[1] for d in devs[kind]})
        for dev, sect, name in devs[kind]:
            L.append(f"%i{dev:04X}%=KEX_{sect},PCI\\VEN_8086&DEV_{dev:04X}")
        L += ["", "[ControlFlags]"] + [f"ExcludeFromSelect=PCI\\VEN_8086&DEV_{d[0]:04X}" for d in devs[kind]] + [""]
        for sect in used:
            L += [f"[KEX_{sect}]"] + sections[sect] + [""]
            if sect == "DUAL_GOOD_IDE":
                # the two channel device nodes (MF\GOODPRIMARY, MF\GOODSECONDARY) that
                # ESDI_506.PDR or kexata.mpd then drive, as mshdc.inf makes them:
                # legacy ports and IRQ of each channel, and its half of the bus master
                # registers (resource 6, 8 bytes at offset 0 or 8)
                L += ["[KEX_DUAL_GOOD_IDE.HW]", "AddReg=KEX_DUAL_GOOD_IDE.RegHW", "",
                      "[KEX_DUAL_GOOD_IDE.RegHW]",
                      "HKR,Child0000,HardwareID,,MF\\GOODPRIMARY",
                      "HKR,Child0000,ResourceMap,1,00,01,02",
                      "HKR,Child0000,VaryingResourceMap,1,06,00,00,00,00,08,00,00,00,01,00,00,00",
                      "HKR,Child0000,MFFlags,1,0C,00,00,00",
                      "HKR,Child0001,HardwareID,,MF\\GOODSECONDARY",
                      "HKR,Child0001,ResourceMap,1,03,04,05",
                      "HKR,Child0001,VaryingResourceMap,1,06,08,00,00,00,08,00,00,00,01,00,00,00",
                      "HKR,Child0001,MFFlags,1,0C,00,00,00",
                      "HKR,,PCIDualIDE,1,01", "",
                      "[KEX_DUAL_GOOD_IDE.PosDup]", "*PNP0600", ""]
        L += regs[kind]
        L += common_tail + [f'i{dev:04X}="{name}"' for dev, _, name in devs[kind]]
        (outdir / fname).write_bytes(("\r\n".join(L) + "\r\n").encode("cp1252", errors="replace"))
        print(f"{outdir / fname}: {len(devs[kind])} devices")
    # for setup: the devices to re-detect if Windows found no driver for them before
    allids = sorted({d[0] for v in devs.values() for d in v})
    # NSIS strings hold 1024 characters: chunks of 150 IDs, ";2570;2571;...;"
    chunks = [allids[i:i + 150] for i in range(0, len(allids), 150)]
    lines = ["; generated by drivers/chipset/gen_inf.py: Intel device IDs the chipset INFs name",
             f"!define KEXCHIP_NCHUNKS {len(chunks)}"]
    for i, c in enumerate(chunks):
        lines.append(f'!define KEXCHIP_IDS{i} ";' + ";".join(f"{d:04X}" for d in c) + ';"')
    (outdir / "kexchip_ids.nsh").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
