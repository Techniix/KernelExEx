#!/usr/bin/env python3
"""Generate kexac97.inf (Windows 98 SE / ME WDM audio, the way 98 SE's own
WDM audio INFs register a PortCls adapter).

usage: gen_inf.py OUT_INF
"""
import sys
from pathlib import Path

# AC'97 audio controllers with the Intel ICH register layout
DEVS = [
    (0x8086, 0x2415, "Intel 82801AA (ICH) AC'97 Audio Controller"),
    (0x8086, 0x2425, "Intel 82801AB (ICH0) AC'97 Audio Controller"),
    (0x8086, 0x2445, "Intel 82801BA (ICH2) AC'97 Audio Controller"),
    (0x8086, 0x2485, "Intel 82801CA (ICH3) AC'97 Audio Controller"),
    (0x8086, 0x24C5, "Intel 82801DB (ICH4) AC'97 Audio Controller"),
    (0x8086, 0x24D5, "Intel 82801EB (ICH5) AC'97 Audio Controller"),
    (0x8086, 0x25A6, "Intel 6300ESB AC'97 Audio Controller"),
    (0x8086, 0x266E, "Intel 82801FB (ICH6) AC'97 Audio Controller"),
    (0x8086, 0x27DE, "Intel 82801G (ICH7) AC'97 Audio Controller"),
    (0x8086, 0x7195, "Intel 82440MX AC'97 Audio Controller"),
    (0x10DE, 0x01B1, "nVidia nForce AC'97 Audio Controller"),
    (0x10DE, 0x006A, "nVidia nForce2 AC'97 Audio Controller"),
    (0x10DE, 0x008A, "nVidia nForce2 400 AC'97 Audio Controller"),
    (0x10DE, 0x00DA, "nVidia nForce3 AC'97 Audio Controller"),
    (0x10DE, 0x00EA, "nVidia nForce3 250 AC'97 Audio Controller"),
    (0x10DE, 0x003A, "nVidia MCP04 AC'97 Audio Controller"),
    (0x10DE, 0x0059, "nVidia nForce4 (CK804) AC'97 Audio Controller"),
    (0x10DE, 0x026B, "nVidia MCP51 AC'97 Audio Controller"),
    (0x1022, 0x746D, "AMD-8111 AC'97 Audio Controller"),
    (0x1022, 0x7445, "AMD-768 AC'97 Audio Controller"),
]

PROXY = "{17CCA71B-ECD7-11D0-B908-00A0C9223196}"


def main():
    out = Path(sys.argv[1])
    L = ["; kexac97.inf - KernelExEx AC'97 audio (Intel ICH and compatibles) for Windows 98 SE / ME",
         "; Generated by drivers/audio/ac97/gen_inf.py. Do not edit.", "",
         "[Version]", 'Signature="$CHICAGO$"', "Class=MEDIA", "ClassGUID={4d36e96c-e325-11ce-bfc1-08002be10318}",
         "Provider=%KEX%", "LayoutFile=layout.inf, layout1.inf, layout2.inf", "DriverVer=11/11/2026, 1.0.0.0", "",
         "[Manufacturer]", "%KEX%=Models", "", "[Models]"]
    for v, p, _ in DEVS:
        L.append(f"%a{v:04X}{p:04X}%=KexAc97,PCI\\VEN_{v:04X}&DEV_{p:04X}")
    L += ["", "[KexAc97]", "Include=ks.inf, wdmaudio.inf", "Needs=KS.Registration, WDMAUDIO.Registration",
          "CopyFiles=KexAc97.CopyList", "AddReg=KexAc97.AddReg", "",
          "[KexAc97.Interfaces]",
          "AddInterface=%KSCATEGORY_AUDIO%,%KSNAME_Wave%,KexAc97.Interface.Wave",
          "AddInterface=%KSCATEGORY_RENDER%,%KSNAME_Wave%,KexAc97.Interface.Wave",
          "AddInterface=%KSCATEGORY_AUDIO%,%KSNAME_Topology%,KexAc97.Interface.Topology", "",
          "[KexAc97.Interface.Wave]", "AddReg=KexAc97.Interface.Wave.AddReg", "",
          "[KexAc97.Interface.Wave.AddReg]", "HKR,,CLSID,,%Proxy.CLSID%", "HKR,,FriendlyName,,%Wave.szPname%", "",
          "[KexAc97.Interface.Topology]", "AddReg=KexAc97.Interface.Topo.AddReg", "",
          "[KexAc97.Interface.Topo.AddReg]", "HKR,,CLSID,,%Proxy.CLSID%", "HKR,,FriendlyName,,%Topology.szPname%", "",
          "[KexAc97.AddReg]",
          'HKR,,AssociatedFilters,,"wdmaud,swmidi,redbook"',
          "HKR,,Driver,,kexac97.sys", "HKR,,NTMPDriver,,kexac97.sys",
          'HKR,Drivers,SubClasses,,"wave,midi,mixer"',
          "HKR,Drivers\\wave\\wdmaud.drv,Driver,,wdmaud.drv",
          "HKR,Drivers\\midi\\wdmaud.drv,Driver,,wdmaud.drv",
          "HKR,Drivers\\mixer\\wdmaud.drv,Driver,,wdmaud.drv",
          "HKR,Drivers\\wave\\wdmaud.drv,Description,,%Desc%",
          "HKR,Drivers\\midi\\wdmaud.drv,Description,,%MIDI%",
          "HKR,Drivers\\mixer\\wdmaud.drv,Description,,%Desc%", "",
          "[KexAc97.CopyList]", "kexac97.sys", "",
          "[DestinationDirs]", "KexAc97.CopyList=10,system32\\drivers", "",
          "[SourceDisksNames]", "1=%DISK%,,", "", "[SourceDisksFiles]", "kexac97.sys=1", "",
          "[Strings]", 'KEX="KernelExEx"', 'DISK="KernelExEx drivers"', 'Desc="AC\'97 Audio (KernelExEx)"',
          'MIDI="AC\'97 Audio MIDI (software synthesizer)"', 'Wave.szPname="AC\'97 Audio"',
          'Topology.szPname="AC\'97 Audio Mixer"', f'Proxy.CLSID="{PROXY}"',
          'KSCATEGORY_AUDIO="{6994AD04-93EF-11D0-A3CC-00A0C9223196}"',
          'KSCATEGORY_RENDER="{65E8773E-8F56-11D0-A3B9-00A0C9223196}"',
          'KSNAME_Wave="Wave"', 'KSNAME_Topology="Topology"']
    for v, p, n in DEVS:
        L.append(f'a{v:04X}{p:04X}="{n}"')
    out.write_bytes(("\r\n".join(L) + "\r\n").encode("cp1252"))
    print(f"{out}: {len(DEVS)} devices")


if __name__ == "__main__":
    main()
