#!/usr/bin/env python3
"""Generate kexhda.inf (Windows 98 SE / ME WDM audio, the way 98 SE's own
WDM audio INFs register a PortCls adapter).

usage: gen_inf.py OUT_INF
"""
import sys
from pathlib import Path

# Intel High Definition Audio controllers (the spec's register layout)
DEVS = [
    (0x8086, 0x2668, "Intel 82801FB (ICH6) High Definition Audio Controller"),
    (0x8086, 0x27D8, "Intel 82801G (ICH7) High Definition Audio Controller"),
    (0x8086, 0x269A, "Intel 631xESB/632xESB High Definition Audio Controller"),
    (0x8086, 0x284B, "Intel 82801H (ICH8) High Definition Audio Controller"),
    (0x8086, 0x293E, "Intel 82801I (ICH9) High Definition Audio Controller"),
    (0x8086, 0x293F, "Intel 82801I (ICH9) High Definition Audio Controller"),
    (0x8086, 0x3A3E, "Intel 82801JI (ICH10) High Definition Audio Controller"),
    (0x8086, 0x3A6E, "Intel 82801JD (ICH10) High Definition Audio Controller"),
    (0x8086, 0x3B56, "Intel 5 Series/3400 Series High Definition Audio Controller"),
    (0x8086, 0x3B57, "Intel 5 Series/3400 Series High Definition Audio Controller"),
    (0x8086, 0x1C20, "Intel 6 Series/C200 Series High Definition Audio Controller"),
    (0x8086, 0x1E20, "Intel 7 Series/C216 High Definition Audio Controller"),
    (0x8086, 0x8C20, "Intel 8 Series/C220 High Definition Audio Controller"),
    (0x8086, 0x811B, "Intel US15W (Poulsbo) High Definition Audio Controller"),
]

PROXY = "{17CCA71B-ECD7-11D0-B908-00A0C9223196}"


def main():
    out = Path(sys.argv[1])
    L = ["; kexhda.inf - KernelExEx HD Audio (Intel High Definition Audio) for Windows 98 SE / ME",
         "; Generated by drivers/audio/hda/gen_inf.py. Do not edit.", "",
         "[Version]", 'Signature="$CHICAGO$"', "Class=MEDIA", "ClassGUID={4d36e96c-e325-11ce-bfc1-08002be10318}",
         "Provider=%KEX%", "LayoutFile=layout.inf, layout1.inf, layout2.inf", "DriverVer=11/11/2026, 1.0.0.0", "",
         "[Manufacturer]", "%KEX%=Models", "", "[Models]"]
    for v, p, _ in DEVS:
        L.append(f"%a{v:04X}{p:04X}%=KexHda,PCI\\VEN_{v:04X}&DEV_{p:04X}")
    L += ["", "[KexHda]", "Include=ks.inf, wdmaudio.inf", "Needs=KS.Registration, WDMAUDIO.Registration",
          "CopyFiles=KexHda.CopyList,KexHda.WdmDrv,KexHda.WdmSys", "AddReg=KexHda.AddReg", "",
          "[KexHda.Interfaces]",
          "AddInterface=%KSCATEGORY_AUDIO%,%KSNAME_Wave%,KexHda.Interface.Wave",
          "AddInterface=%KSCATEGORY_RENDER%,%KSNAME_Wave%,KexHda.Interface.Wave",
          "AddInterface=%KSCATEGORY_AUDIO%,%KSNAME_Topology%,KexHda.Interface.Topology", "",
          "[KexHda.Interface.Wave]", "AddReg=KexHda.Interface.Wave.AddReg", "",
          "[KexHda.Interface.Wave.AddReg]", "HKR,,CLSID,,%Proxy.CLSID%", "HKR,,FriendlyName,,%Wave.szPname%", "",
          "[KexHda.Interface.Topology]", "AddReg=KexHda.Interface.Topo.AddReg", "",
          "[KexHda.Interface.Topo.AddReg]", "HKR,,CLSID,,%Proxy.CLSID%", "HKR,,FriendlyName,,%Topology.szPname%", "",
          "[KexHda.AddReg]",
          'HKR,,AssociatedFilters,,"wdmaud,swmidi,redbook"',
          "HKR,,Driver,,kexhda.sys", "HKR,,NTMPDriver,,kexhda.sys",
          'HKR,Drivers,SubClasses,,"wave,midi,mixer"',
          "HKR,Drivers\\wave\\wdmaud.drv,Driver,,wdmaud.drv",
          "HKR,Drivers\\midi\\wdmaud.drv,Driver,,wdmaud.drv",
          "HKR,Drivers\\mixer\\wdmaud.drv,Driver,,wdmaud.drv",
          "HKR,Drivers\\wave\\wdmaud.drv,Description,,%Desc%",
          "HKR,Drivers\\midi\\wdmaud.drv,Description,,%MIDI%",
          "HKR,Drivers\\mixer\\wdmaud.drv,Description,,%Desc%", "",
          "[KexHda.CopyList]", "kexhda.sys", "",
          # Windows' own WDM audio files, from the Windows 98 CD (layout*.inf).
          # On 98 SE wdmaudio.inf copies them only later, from a RunOnce entry
          # at the next logon; listed here, a PC that never had a WDM sound
          # card asks for the CD now and the driver starts straight away.
          "[KexHda.WdmDrv]", "portcls.sys", "stream.sys", "ks.sys", "kmixer.sys", "sysaudio.sys",
          "swmidi.sys", "wdmaud.sys", "redbook.sys", "sbemul.sys", "",
          "[KexHda.WdmSys]", "wdmaud.drv", "ksuser.dll", "",
          "[DestinationDirs]", "KexHda.CopyList=10,system32\\drivers", "KexHda.WdmDrv=10,system32\\drivers", "KexHda.WdmSys=11", "",
          "[SourceDisksNames]", "1=%DISK%,,", "", "[SourceDisksFiles]", "kexhda.sys=1", "",
          "[Strings]", 'KEX="KernelExEx"', 'DISK="KernelExEx drivers"', 'Desc="HD Audio (KernelExEx)"',
          'MIDI="HD Audio MIDI (software synthesizer)"', 'Wave.szPname="HD Audio"',
          'Topology.szPname="HD Audio Mixer"', f'Proxy.CLSID="{PROXY}"',
          'KSCATEGORY_AUDIO="{6994AD04-93EF-11D0-A3CC-00A0C9223196}"',
          'KSCATEGORY_RENDER="{65E8773E-8F56-11D0-A3B9-00A0C9223196}"',
          'KSNAME_Wave="Wave"', 'KSNAME_Topology="Topology"']
    for v, p, n in DEVS:
        L.append(f'a{v:04X}{p:04X}="{n}"')
    out.write_bytes(("\r\n".join(L) + "\r\n").encode("cp1252"))
    print(f"{out}: {len(DEVS)} devices")


if __name__ == "__main__":
    main()
