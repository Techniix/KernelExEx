#!/usr/bin/env python3
"""Generate kexathn.inf from OpenBSD's if_athn_pci.c (its athn_pci_devices
table) and pcidevs.h (the chip names).

usage: gen_inf.py IF_ATHN_PCI_C PCIDEVS_H OUT_INF
"""
import re
import sys
from pathlib import Path


def main():
    src, devs, out = (Path(a) for a in sys.argv[1:4])
    s = src.read_text()
    table = s[s.index("athn_pci_devices[]"):]
    table = table[:table.index("};")]
    names = re.findall(r"PCI_PRODUCT_ATHEROS_(\w+)", table)
    d = devs.read_text()
    ids = []
    for n in names:
        m = re.search(rf"#define\s+PCI_PRODUCT_ATHEROS_{n}\s+0x([0-9a-fA-F]+)\s+/\*\s*(.*?)\s*\*/", d)
        ids.append((int(m.group(1), 16), m.group(2)))
    L = ["; kexathn.inf - KernelExEx Atheros PCI/PCIe Wi-Fi (OpenBSD athn, OpenBSD net80211) for Windows 98 SE / ME",
         "; Generated by drivers/kexnet/athn/gen_inf.py from OpenBSD if_athn_pci.c and pcidevs. Do not edit.", "",
         "[Version]", 'Signature="$CHICAGO$"', "Class=Net", "ClassGUID={4d36e972-e325-11ce-bfc1-08002be10318}",
         "Provider=%KEX%", "", "[Manufacturer]", "%ATH%=Atheros", "", "[Atheros]"]
    L += [f"%athn_{i:04X}%=athn_{i:04X}.ndi,PCI\\VEN_168C&DEV_{i:04X}" for i, _ in ids]
    L.append("")
    for i, _ in ids:
        L += [f"[athn_{i:04X}.ndi]", f"AddReg=athn_{i:04X}.id,athn.reg,athn.params", "CopyFiles=athn.copy",
              f"DeviceID=PCI\\VEN_168C&DEV_{i:04X}", "MaxInstance=4", "",
              f"[athn_{i:04X}.id]", f'HKR,Ndi,DeviceID,,"PCI\\VEN_168C&DEV_{i:04X}"', "HKR,Ndi,MaxInstance,,4", ""]
    L += ["[athn.reg]", 'HKR,,DevLoader,,"*ndis"', "HKR,,DeviceVxDs,,kexathn.sys",
          'HKR,,EnumPropPages,,"netdi.dll,EnumPropPages"', "HKR,NDIS,LogDriverName,,kexathn",
          "HKR,NDIS,MajorNdisVersion,1,05", "HKR,NDIS,MinorNdisVersion,1,00", "HKR,Ndi,HelpText,,%HELP%",
          'HKR,Ndi\\Interfaces,DefUpper,,"ndis3"', 'HKR,Ndi\\Interfaces,DefLower,,"ethernet"',
          'HKR,Ndi\\Interfaces,UpperRange,,"ndis3"', 'HKR,Ndi\\Interfaces,LowerRange,,"ethernet"',
          "HKR,Ndi\\Install,ndis3,,athn.ndis3", "",
          "[athn.params]",
          "HKR,Ndi\\params\\NetworkName,ParamDesc,,%SSID%", "HKR,Ndi\\params\\NetworkName,type,,edit",
          "HKR,Ndi\\params\\NetworkName,LimitText,,32", "HKR,Ndi\\params\\NetworkName,default,,",
          "HKR,Ndi\\params\\Passphrase,ParamDesc,,%PASS%", "HKR,Ndi\\params\\Passphrase,type,,edit",
          "HKR,Ndi\\params\\Passphrase,LimitText,,64", "HKR,Ndi\\params\\Passphrase,default,,",
          "HKR,Ndi\\params\\AllowTKIP,ParamDesc,,%TKIP%", "HKR,Ndi\\params\\AllowTKIP,type,,enum",
          "HKR,Ndi\\params\\AllowTKIP,default,,0", "HKR,Ndi\\params\\AllowTKIP\\enum,0,,%NO%",
          "HKR,Ndi\\params\\AllowTKIP\\enum,1,,%YES%", "HKR,,AllowTKIP,,0",
          "HKR,Ndi\\params\\NetworkAddress,ParamDesc,,%NETADDR%", "HKR,Ndi\\params\\NetworkAddress,type,,edit",
          "HKR,Ndi\\params\\NetworkAddress,LimitText,,12", "HKR,Ndi\\params\\NetworkAddress,optional,,1", "",
          "[athn.ndis3]   ; netdi runs this with no source path: the files come from the device section", "",
          "[athn.copy]", "kexathn.sys", "kexbsd.sys", "",
          "[DestinationDirs]", "athn.copy=11", "",
          "[SourceDisksNames]", "1=%DISK%,,", "",
          "[SourceDisksFiles]", "kexathn.sys=1", "kexbsd.sys=1", "",
          "[Strings]", 'KEX="KernelExEx"', 'ATH="Atheros"', 'DISK="KernelExEx drivers"',
          'SSID="Network name (SSID)"', 'PASS="WPA2 passphrase (empty: open network)"',
          'TKIP="Allow older WPA (TKIP, less secure)"', 'NO="No"', 'YES="Yes"', 'NETADDR="Network Address"',
          'HELP="Atheros 802.11n Wi-Fi adapter, driven by the OpenBSD athn driver and wireless stack through '
          'KernelExEx kexbsd. Set the network name and passphrase on the Advanced tab."']
    L += [f'athn_{i:04X}="Atheros {name} Wireless Network Adapter (KernelExEx)"' for i, name in ids]
    out.write_bytes(("\r\n".join(L) + "\r\n").encode("ascii"))
    print(f"{out}: {len(ids)} devices")


if __name__ == "__main__":
    main()
