#!/usr/bin/env python3
"""Generate kexrl.inf from the rl_devs[] table in kexrl.c, so the INF lists
exactly what the driver claims.

usage: gen_inf.py KEXRL_C OUT_INF
"""
import re
import sys
from pathlib import Path


def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    s = src.read_text()
    table = s[s.index("rl_devs[] = {"):]
    table = table[:table.index("};")]
    ids = []
    for v, p, c in re.findall(r"\{\s*0x([0-9a-fA-F]{4}),\s*0x([0-9a-fA-F]{4})\s*\},\s*/\*\s*(.*?)\s*\*/", table):
        v, p = int(v, 16), int(p, 16)
        if (v, p) == (0x10EC, 0x8129):
            continue   # listed in the table to say we leave it alone
        name = "Realtek RTL8139/810x Fast Ethernet" if v == 0x10EC else c.split(",")[0].split(" (")[0]
        ids.append((v, p, name))
    L = ["; kexrl.inf - KernelExEx Realtek RTL8139/810x Fast Ethernet for Windows 98 SE / ME",
         "; Generated by drivers/kexnet/rl/gen_inf.py from kexrl.c. Do not edit.", "",
         "[Version]", 'Signature="$CHICAGO$"', "Class=Net", "ClassGUID={4d36e972-e325-11ce-bfc1-08002be10318}",
         "Provider=%KEX%", "", "[Manufacturer]", "%RTK%=Models", "", "[Models]"]
    for v, p, _ in ids:
        L.append(f"%rl_{v:04X}{p:04X}%=rl_{v:04X}{p:04X}.ndi,PCI\\VEN_{v:04X}&DEV_{p:04X}")
    for v, p, _ in ids:
        pid = f"PCI\\VEN_{v:04X}&DEV_{p:04X}"
        L += ["", f"[rl_{v:04X}{p:04X}.ndi]", f"AddReg=rl_{v:04X}{p:04X}.id,kexrl.reg,kexrl.params",
              "CopyFiles=kexrl.copy", f"DeviceID={pid}", "MaxInstance=8", "",
              f"[rl_{v:04X}{p:04X}.id]", f'HKR,Ndi,DeviceID,,"{pid}"', "HKR,Ndi,MaxInstance,,8"]
    L += ["", "[kexrl.reg]", 'HKR,,DevLoader,,"*ndis"', "HKR,,DeviceVxDs,,kexrl.sys",
          'HKR,,EnumPropPages,,"netdi.dll,EnumPropPages"', "HKR,NDIS,LogDriverName,,kexrl",
          "HKR,NDIS,MajorNdisVersion,1,05", "HKR,NDIS,MinorNdisVersion,1,00", "HKR,Ndi,HelpText,,%HELP%",
          'HKR,Ndi\\Interfaces,DefUpper,,"ndis3"', 'HKR,Ndi\\Interfaces,DefLower,,"ethernet"',
          'HKR,Ndi\\Interfaces,UpperRange,,"ndis3"', 'HKR,Ndi\\Interfaces,LowerRange,,"ethernet"',
          "HKR,Ndi\\Install,ndis3,,kexrl.ndis3", "",
          "[kexrl.ndis3]   ; netdi runs this with no source path: the files come from the device section", "",
          "[kexrl.params]",
          "HKR,Ndi\\params\\NetworkAddress,ParamDesc,,%NETADDR%", "HKR,Ndi\\params\\NetworkAddress,type,,edit",
          "HKR,Ndi\\params\\NetworkAddress,LimitText,,12", "HKR,Ndi\\params\\NetworkAddress,UpperCase,,1",
          "HKR,Ndi\\params\\NetworkAddress,optional,,1", "",
          "[kexrl.copy]", "kexrl.sys", "kexbsd.sys", "",
          "[DestinationDirs]", "kexrl.copy=11", "",
          "[SourceDisksNames]", "1=%DISK%,,", "",
          "[SourceDisksFiles]", "kexrl.sys=1", "kexbsd.sys=1", "",
          "[Strings]", 'KEX="KernelExEx"', 'RTK="Realtek"', 'DISK="KernelExEx drivers"', 'NETADDR="Network Address"',
          'HELP="Realtek RTL8139/810x family Fast Ethernet adapter (KernelExEx kexrl)."']
    for v, p, n in ids:
        L.append(f'rl_{v:04X}{p:04X}="{n}"')
    out.write_bytes(("\r\n".join(L) + "\r\n").encode("cp1252"))
    print(f"{out}: {len(ids)} devices")


if __name__ == "__main__":
    main()
