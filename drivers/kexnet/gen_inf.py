#!/usr/bin/env python3
"""Generate kexem.inf from OpenBSD's em_devices[] table (if_em.c) and the
PCI ID database (pcidevs), so the INF matches exactly what the driver claims.

usage: gen_inf.py IF_EM_C PCIDEVS OUT_INF
"""
import re
import sys
from pathlib import Path


def main():
    if_em, pcidevs, out = map(Path, sys.argv[1:4])
    src = if_em.read_text()
    table = src[src.index("em_devices[] = {"):]
    table = table[:table.index("};")]
    # EP80579 (ICP_xxxx) needs its GCU companion function: not supported (kexem.c)
    names = [n for n in re.findall(r"PCI_PRODUCT_INTEL_(\w+)", table) if not n.startswith("EP80579")]
    ids, descs = {}, {}
    for line in pcidevs.read_text().splitlines():
        m = re.match(r"product\s+INTEL\s+(\w+)\s+0x([0-9a-fA-F]+)\s+(.*)", line)
        if m:
            ids[m.group(1)] = int(m.group(2), 16)
            descs[m.group(1)] = m.group(3).strip()
    missing = [n for n in names if n not in ids]
    if missing:
        sys.exit("not in pcidevs: " + ", ".join(missing))
    seen = []
    for n in names:
        if ids[n] not in [ids[s] for s in seen]:
            seen.append(n)
    lines = [
        "; kexem.inf - KernelExEx Intel PRO/1000 (OpenBSD em) for Windows 98 SE / ME",
        "; Generated by drivers/kexnet/gen_inf.py from OpenBSD if_em.c and pcidevs. Do not edit.",
        "",
        "[Version]",
        'Signature="$CHICAGO$"',
        "Class=Net",
        "ClassGUID={4d36e972-e325-11ce-bfc1-08002be10318}",
        "Provider=%KEX%",
        "",
        "[Manufacturer]",
        "%INTEL%=Intel",
        "",
        "[Intel]",
    ]
    for n in seen:
        lines.append(f"%em_{ids[n]:04X}%=em_{ids[n]:04X}.ndi,PCI\\VEN_8086&DEV_{ids[n]:04X}")
    # Windows 9x's network class installer (netdi) only takes a device as a
    # network component, and binds protocols to it, with its DeviceID in the
    # install section and under Ndi; so every device gets its own section.
    for n in seen:
        pid = f"PCI\\VEN_8086&DEV_{ids[n]:04X}"
        lines += ["", f"[em_{ids[n]:04X}.ndi]", f"AddReg=em_{ids[n]:04X}.id,kexem.reg,kexem.params",
                  "CopyFiles=kexem.sys.copy,kexbsd.copy", f"DeviceID={pid}", "MaxInstance=8",
                  "", f"[em_{ids[n]:04X}.id]", f'HKR,Ndi,DeviceID,,"{pid}"', 'HKR,Ndi,MaxInstance,,8']
    lines += [
        "",
        "[kexem.reg]",
        'HKR,,DevLoader,,"*ndis"',
        "HKR,,DeviceVxDs,,kexem.sys",
        'HKR,,EnumPropPages,,"netdi.dll,EnumPropPages"',
        "HKR,NDIS,LogDriverName,,kexem",
        "HKR,NDIS,MajorNdisVersion,1,05",
        "HKR,NDIS,MinorNdisVersion,1,00",
        "HKR,Ndi,HelpText,,%HELP%",
        'HKR,Ndi\\Interfaces,DefUpper,,"ndis3"',
        'HKR,Ndi\\Interfaces,DefLower,,"ethernet"',
        'HKR,Ndi\\Interfaces,UpperRange,,"ndis3"',
        'HKR,Ndi\\Interfaces,LowerRange,,"ethernet"',
        "HKR,Ndi\\Install,ndis3,,kexem.ndis3",
        "",
        "[kexem.ndis3]",   # netdi runs this with no source path: the files come from the device section
        "",
        "[kexem.params]",
        "HKR,Ndi\\params\\NetworkAddress,ParamDesc,,%NETADDR%",
        "HKR,Ndi\\params\\NetworkAddress,type,,edit",
        "HKR,Ndi\\params\\NetworkAddress,LimitText,,12",
        "HKR,Ndi\\params\\NetworkAddress,UpperCase,,1",
        "HKR,Ndi\\params\\NetworkAddress,optional,,1",
        "",
        "[kexem.sys.copy]",
        "kexem.sys",
        "",
        "[kexbsd.copy]",
        "kexbsd.sys",
        "",
        "[DestinationDirs]",
        "kexem.sys.copy=11",
        "kexbsd.copy=11",
        "",
        "[SourceDisksNames]",
        "1=%DISK%,,",
        "",
        "[SourceDisksFiles]",
        "kexem.sys=1",
        "kexbsd.sys=1",
        "",
        "[Strings]",
        'KEX="KernelExEx"',
        'INTEL="Intel"',
        'DISK="KernelExEx drivers"',
        'NETADDR="Network Address"',
        'HELP="Intel PRO/1000 network adapter, driven by the OpenBSD em driver through KernelExEx kexbsd."',
    ]
    for n in seen:
        d = descs[n]
        lines.append(f'em_{ids[n]:04X}="Intel {d} (KernelExEx)"')
    out.write_bytes(("\r\n".join(lines) + "\r\n").encode("cp1252"))
    print(f"{out}: {len(seen)} devices")


if __name__ == "__main__":
    main()
