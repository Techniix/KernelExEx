#!/usr/bin/env python3
"""Generate kexurtwn.inf from OpenBSD's urtwn_devs[] (if_urtwn.c) and usbdevs.h.

usage: gen_inf.py IF_URTWN_C USBDEVS_H OUT_INF
"""
import re
import sys
from pathlib import Path


def main():
    src, usbdevs, out = map(Path, sys.argv[1:4])
    s = src.read_text()
    table = s[s.index("urtwn_devs[] = {"):]
    table = table[:table.index("};")]
    ent = re.findall(r"URTWN_DEV(?:_[0-9A-Z]+)?\(\s*(\w+),\s*(\w+)\s*\)", table)
    defs = {}
    for line in usbdevs.read_text().splitlines():
        m = re.match(r"#define\s+(USB_(?:VENDOR|PRODUCT)_\w+)\s+0x([0-9a-fA-F]+)", line)
        if m:
            defs[m.group(1)] = int(m.group(2), 16)
    ids = []
    for v, p in ent:
        vid, pid = defs.get(f"USB_VENDOR_{v}"), defs.get(f"USB_PRODUCT_{v}_{p}")
        if vid is None or pid is None:
            sys.exit(f"unknown {v} {p}")
        if (vid, pid) not in [(a, b) for a, b, _ in ids]:
            ids.append((vid, pid, f"{v.title()} {p}"))
    L = ["; kexurtwn.inf - KernelExEx Realtek USB Wi-Fi (OpenBSD urtwn) for Windows 98 SE / ME",
         "; Generated by drivers/kexnet/urtwn/gen_inf.py from OpenBSD if_urtwn.c and usbdevs.h. Do not edit.", "",
         "[Version]", 'Signature="$CHICAGO$"', "Class=Net", "ClassGUID={4d36e972-e325-11ce-bfc1-08002be10318}",
         "Provider=%KEX%", "", "[Manufacturer]", "%RTK%=Models", "", "[Models]"]
    for vid, pid, d in ids:
        L.append(f"%u{vid:04X}{pid:04X}%=u{vid:04X}{pid:04X}.ndi,USB\\VID_{vid:04X}&PID_{pid:04X}")
    for vid, pid, d in ids:
        pid_s = f"USB\\VID_{vid:04X}&PID_{pid:04X}"
        L += ["", f"[u{vid:04X}{pid:04X}.ndi]", f"AddReg=u{vid:04X}{pid:04X}.id,urtwn.reg,urtwn.params",
              "CopyFiles=urtwn.copy,urtwn.fw", f"DeviceID={pid_s}", "MaxInstance=4", "",
              f"[u{vid:04X}{pid:04X}.id]", f'HKR,Ndi,DeviceID,,"{pid_s}"', "HKR,Ndi,MaxInstance,,4"]
    L += ["", "[urtwn.reg]", 'HKR,,DevLoader,,"*ndis"', "HKR,,DeviceVxDs,,kexurtwn.sys",
          'HKR,,EnumPropPages,,"netdi.dll,EnumPropPages"', "HKR,NDIS,LogDriverName,,kexurtwn",
          "HKR,NDIS,MajorNdisVersion,1,05", "HKR,NDIS,MinorNdisVersion,1,00", "HKR,Ndi,HelpText,,%HELP%",
          'HKR,Ndi\\Interfaces,DefUpper,,"ndis3"', 'HKR,Ndi\\Interfaces,DefLower,,"ethernet"',
          'HKR,Ndi\\Interfaces,UpperRange,,"ndis3"', 'HKR,Ndi\\Interfaces,LowerRange,,"ethernet"',
          "HKR,Ndi\\Install,ndis3,,urtwn.ndis3", "",
          "[urtwn.params]",
          "HKR,Ndi\\params\\NetworkName,ParamDesc,,%SSID%",
          "HKR,Ndi\\params\\NetworkName,type,,edit",
          "HKR,Ndi\\params\\NetworkName,LimitText,,32",
          "HKR,Ndi\\params\\NetworkName,default,,",
          "HKR,Ndi\\params\\Passphrase,ParamDesc,,%PASS%",
          "HKR,Ndi\\params\\Passphrase,type,,edit",
          "HKR,Ndi\\params\\Passphrase,LimitText,,64",
          "HKR,Ndi\\params\\Passphrase,default,,",
          "HKR,Ndi\\params\\AllowTKIP,ParamDesc,,%TKIP%",
          "HKR,Ndi\\params\\AllowTKIP,type,,enum",
          "HKR,Ndi\\params\\AllowTKIP,default,,0",
          "HKR,Ndi\\params\\AllowTKIP\\enum,0,,%NO%",
          "HKR,Ndi\\params\\AllowTKIP\\enum,1,,%YES%",
          "HKR,,AllowTKIP,,0",
          "HKR,Ndi\\params\\NetworkAddress,ParamDesc,,%NETADDR%",
          "HKR,Ndi\\params\\NetworkAddress,type,,edit",
          "HKR,Ndi\\params\\NetworkAddress,LimitText,,12",
          "HKR,Ndi\\params\\NetworkAddress,optional,,1", "",
          "[urtwn.ndis3]   ; netdi runs this with no source path: the files come from the device section", "",
          "[urtwn.copy]", "kexurtwn.sys", "kexbsd.sys", "",
          "[urtwn.fw]", "8188EU.FW", "8192CU.FW", "8192CT.FW", "8192EU.FW", "",
          "[DestinationDirs]", "urtwn.copy=11", "urtwn.fw=11,KEXFW", "",
          "[SourceDisksNames]", "1=%DISK%,,", "",
          "[SourceDisksFiles]", "kexurtwn.sys=1", "kexbsd.sys=1", "8188EU.FW=1", "8192CU.FW=1", "8192CT.FW=1",
          "8192EU.FW=1", "",
          "[Strings]", 'KEX="KernelExEx"', 'RTK="Realtek"', 'DISK="KernelExEx drivers"',
          'SSID="Network name (SSID)"', 'PASS="WPA2 passphrase (empty: open network)"',
          'TKIP="Allow older WPA (TKIP, less secure)"', 'NO="No"', 'YES="Yes"', 'NETADDR="Network Address"',
          'HELP="Realtek USB Wi-Fi adapter, driven by the OpenBSD urtwn driver and wireless stack through KernelExEx kexbsd. Set the network name and passphrase on the Advanced tab."']
    for vid, pid, d in ids:
        L.append(f'u{vid:04X}{pid:04X}="Realtek USB Wi-Fi {vid:04X}:{pid:04X} (KernelExEx)"')
    out.write_bytes(("\r\n".join(L) + "\r\n").encode("cp1252"))
    print(f"{out}: {len(ids)} devices")


if __name__ == "__main__":
    main()
