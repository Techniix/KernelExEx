#!/usr/bin/env python3
"""Generate kexehci.inf: every USB 2.0 (EHCI) host controller, by name from
pci.ids (pciutils, GPLv2 or BSD-3) and by its PCI class (PCI\\CC_0C0320) for
the ones pci.ids does not name, so that any EHCI controller gets the driver.

usage: gen_inf.py PCI_IDS OUT_INF
"""
import re
import sys
from pathlib import Path

SKIP = ("xhci", "usb 3", "otg", "peripheral", "device controller", "virtual feature", "dual role")


def wanted(name):
    n = name.lower()
    if any(s in n for s in SKIP):
        return False
    return "ehci" in n or "usb2" in n or "usb 2.0" in n or "enhanced host" in n


def read(ids):
    out = []
    vendor = vname = None
    for line in Path(ids).read_text(encoding="utf-8", errors="replace").splitlines():
        if line.startswith("C "):
            break
        if not line or line.startswith("#"):
            continue
        m = re.match(r"^([0-9a-f]{4})\s+(.*)", line)
        if m:
            vendor, vname = int(m.group(1), 16), m.group(2).strip()
            continue
        m = re.match(r"^\t([0-9a-f]{4})\s+(.*)", line)
        if m and vendor is not None and wanted(m.group(2)):
            out.append((vendor, int(m.group(1), 16), vname, m.group(2).strip()))
    return out


SHORT = {0x8086: "Intel", 0x1106: "VIA", 0x1033: "NEC", 0x10de: "NVIDIA", 0x1002: "AMD", 0x1022: "AMD",
         0x1039: "SiS", 0x10b9: "ALi/ULi", 0x10ec: "Realtek", 0x15ad: "VMware", 0x1131: "NXP"}


def clean(s):
    return s.replace('"', "'").replace("%", "%%")


def main():
    devs = read(sys.argv[1])
    L = ["; kexehci.inf - KernelExEx USB 2.0 (EHCI) host controllers for Windows 98 SE / ME",
         "; Generated by drivers/usb/ehci/gen_inf.py from pci.ids (pciutils, GPLv2 or BSD-3). Do not edit.",
         "; Full- and low-speed devices stay on the USB 1.1 controllers and Windows' own drivers.",
         "",
         "[Version]",
         'Signature="$CHICAGO$"',
         "LayoutFile=layout.inf, layout1.inf, layout2.inf",
         "Class=USB",
         "ClassGUID={36FC9E60-C465-11CF-8056-444553540000}",
         "Provider=%KEX%",
         "DriverVer=11/11/2026, 1.0.0.0",
         "",
         "[Manufacturer]",
         "%KEX%=Models",
         "",
         "[Models]"]
    strings = []
    for v, d, vname, name in devs:
        key = f"e{v:04X}{d:04X}"
        L.append(f"%{key}%=KexEhci,PCI\\VEN_{v:04X}&DEV_{d:04X}")
        vn = SHORT.get(v, vname.split(" [")[0].replace(" Corporation", "").replace(", Inc.", "").replace(" Inc.", ""))
        strings.append(f'{key}="{clean(vn)} {clean(name)} (KernelExEx)"')
    L.append("%generic%=KexEhci,PCI\\CC_0C0320")
    strings.append('generic="USB 2.0 Enhanced Host Controller (KernelExEx)"')
    L += ["",
          "[KexEhci]",
          "AddReg=KexEhci.AddReg",
          "CopyFiles=KexEhci.CopyFiles, KexEhci.Usbd",
          "",
          "[KexEhci.AddReg]",
          "HKR,,DevLoader,,*ntkern",
          "HKR,,NTMPDriver,,kexehci.sys",
          "",
          "[KexEhci.CopyFiles]",
          "kexehci.sys",
          "",
          "; Windows' own USB library, from the Windows 98 CD when no USB 1.1 controller",
          "; installed it yet: Windows' class drivers (hidusb.sys) need it",
          "[KexEhci.Usbd]",
          "usbd.sys,,,0x10",
          "",
          "[DestinationDirs]",
          "KexEhci.CopyFiles=10,system32\\drivers",
          "KexEhci.Usbd=10,system32\\drivers",
          "",
          "[SourceDisksNames]",
          '1="KernelExEx USB 2.0 driver",,0',
          "",
          "[SourceDisksFiles]",
          "kexehci.sys=1",
          "",
          "[Strings]",
          'KEX="KernelExEx"']
    L += strings
    Path(sys.argv[2]).write_text("\r\n".join(L) + "\r\n", encoding="cp1252", errors="replace")
    print(f"{sys.argv[2]}: {len(devs)} named controllers + PCI\\CC_0C0320")


if __name__ == "__main__":
    main()
