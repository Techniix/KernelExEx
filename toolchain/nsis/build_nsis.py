#!/usr/bin/env python3
"""Build NSIS 3.x on Linux for making Windows 9x installers.

  makensis      native (host) compiler
  Stubs, plug-ins (Banner, nsDialogs, NSISdl, StartMenu, System), UI files
                cross-compiled for Windows with clang, dressed up as a
                MinGW toolchain (i686-w64-mingw32-*) so NSIS's SCons build
                accepts it.

Needs the NSIS and SCons sources (both on GitHub: kichik/nsis, SCons/scons),
the SDK from net/tools/prepare_sdk.py, clang/lld/LLVM tools and the zlib
headers. The small runtime pieces here (mem.c, dllcrt2.c, crt2.c, cxx.cpp)
stand in for libgcc, the MinGW start-up objects and libstdc++, which this
setup does not have; NSIS needs very little of them.

Usage: build_nsis.py --nsis-src DIR --scons-src DIR --sdk DIR --core-lib DIR --work DIR --prefix DIR
"""
import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent

XCC = r'''#!/bin/sh
# clang dressed as i686-w64-mingw32-gcc (generated by toolchain/nsis/build_nsis.py)
mode=$1; shift
# lld has no --exclude-libs; drop it (nothing is exported from these images anyway)
for a do shift; case "$a" in -Wl,--exclude-libs,*) ;; *) set -- "$@" "$a";; esac; done
# clang's assembler lacks the gas .func/.endfunc directives (System plug-in): strip them,
# also from files the .S includes, by compiling a filtered copy of its directory
case "$*" in *.S*)
  for a do case "$a" in *.S)
      d=$(mktemp -d); for f in "$(dirname "$a")"/*; do case "$f" in
        *.S|*.s) sed -E '/^[[:space:]]*\.(func|endfunc)([[:space:]]|$)/d' "$f" > "$d/$(basename "$f")";;
        *) [ -f "$f" ] && cp "$f" "$d/";; esac; done
      set -- "$@" "$d/$(basename "$a")";;
    *) set -- "$@" "$a";; esac; shift; done;;
esac
link=yes
for a do case "$a" in -c|-E|-S|-M|-MM) link=no;; esac; done
extra=; [ $link = yes ] && extra=-lgcc   # memcpy/memset/division helpers, even with -nostdlib
exec $mode --target=i686-w64-windows-gnu -march=i586 -mtune=pentium2 -fuse-ld=lld -nostdinc \
  -isystem @RES@/include -isystem @SDK@/include -isystem @MI@/../crt -isystem @MI@ \
  -fno-stack-protector -D__USE_MINGW_ANSI_STDIO=0 -Wno-everything \
  -L@SDK@/lib -L@LIB@ -L@CORELIB@ "$@" $extra
'''

SKIPPLUGINS = ("AdvSplash,BgImage,Dialer,InstallOptions,LangDLL,Library/TypeLib,Math,Splash,UserInfo,"
               "VPatch/Source/Plugin,nsExec")
SKIPUTILS = "Library/RegTool,MakeLangId,Makensisw,NSIS Menu,SubStart,VPatch/Source/GenPat,zip2exe"


def run(cmd, **kw):
    p = subprocess.run([str(c) for c in cmd], **kw)
    if p.returncode:
        sys.exit(f"FAILED: {' '.join(str(c) for c in cmd)}")


def tool(name):
    for cand in (name, name + "-18", f"/usr/lib/llvm-18/bin/{name}"):
        if shutil.which(cand) or Path(cand).exists():
            return shutil.which(cand) or cand
    sys.exit(f"{name} not found")


def main():
    ap = argparse.ArgumentParser()
    for opt in ("--nsis-src", "--scons-src", "--sdk", "--work", "--prefix"):
        ap.add_argument(opt, required=True, type=Path)
    ap.add_argument("--core-lib", required=True, type=Path,
                    help="lib/ of toolchain/build_core.py output (for libuuid.a)")
    ap.add_argument("-j", type=int, default=os.cpu_count() or 4)
    a = ap.parse_args()
    sdk, work = a.sdk.resolve(), a.work.resolve()
    mi = (sdk / "MINGW_INCLUDE").read_text().strip()
    res = subprocess.run(["clang", "-print-resource-dir"], capture_output=True, text=True).stdout.strip()
    bindir, libdir = work / "bin", work / "lib"
    bindir.mkdir(parents=True, exist_ok=True)
    libdir.mkdir(parents=True, exist_ok=True)

    def script(name, body):
        p = bindir / name
        p.write_text(body)
        p.chmod(0o755)

    script("xcc.sh", XCC.replace("@RES@", res).replace("@SDK@", str(sdk)).replace("@MI@", mi)
           .replace("@LIB@", str(libdir)).replace("@CORELIB@", str(a.core_lib.resolve())))
    script("i686-w64-mingw32-gcc", f'#!/bin/sh\nexec "{bindir}/xcc.sh" clang "$@"\n')
    script("i686-w64-mingw32-g++", f'#!/bin/sh\nexec "{bindir}/xcc.sh" clang++ -fno-exceptions -fno-rtti '
           f'-fno-asynchronous-unwind-tables -nostdinc++ -isystem {ROOT / "toolchain/cxx"} "$@"\n')
    for t in ("ar", "ranlib", "strip", "nm", "objcopy"):
        script(f"i686-w64-mingw32-{t}", f'#!/bin/sh\nexec {tool("llvm-" + t)} "$@"\n')
    script("i686-w64-mingw32-windres",
           f'#!/bin/sh\nexec {tool("llvm-windres")} --target=pe-i386 -I{mi} -I{mi}/../crt -I{sdk}/include "$@"\n')

    gcc, gxx = bindir / "i686-w64-mingw32-gcc", bindir / "i686-w64-mingw32-g++"
    # libgcc stand-in: memory and division helpers, stack probes
    objs = []
    for src in (HERE / "mem.c", ROOT / "toolchain/rt/w9xrt_div.c", ROOT / "toolchain/rt/chkstk.S"):
        o = libdir / (src.name + ".o")
        run([gcc, "-O2", "-fno-builtin", "-ffreestanding", "-c", src, "-o", o])
        objs.append(o)
    for name in ("libgcc.a", "libgcc_s.a", "libgcc_eh.a"):
        (libdir / name).unlink(missing_ok=True)
        run([tool("llvm-ar"), "rcs", libdir / name, *objs])
    for name in ("libmingw32.a", "libmingwex.a", "libmoldname.a"):
        (libdir / name).unlink(missing_ok=True)
        run([tool("llvm-ar"), "rcs", libdir / name])
    for src, obj in (("dllcrt2.c", "dllcrt2.o"), ("crt2.c", "crt2.o")):
        run([gcc, "-O2", "-c", HERE / src, "-o", libdir / obj])
    run([gcc, "-x", "c", "-c", "/dev/null", "-o", libdir / "crtbegin.o"])
    shutil.copy(libdir / "crtbegin.o", libdir / "crtend.o")
    # libstdc++ stand-in: one object per function, so a plug-in that defines
    # its own operator new does not pull in a clashing copy
    lines = (HERE / "cxx.cpp").read_text().splitlines()
    pieces = [l for l in lines if l.startswith("void") or l.startswith('extern "C"')]
    cobjs = []
    for i, line in enumerate(pieces):
        s = libdir / f"cxx{i}.cpp"
        s.write_text("#include <windows.h>\n" + line + "\n")
        o = libdir / f"cxx{i}.o"
        run([gxx, "-O2", "-c", s, "-o", o])
        cobjs.append(o)
    (libdir / "libstdc++.a").unlink(missing_ok=True)
    run([tool("llvm-ar"), "rcs", libdir / "libstdc++.a", *cobjs])

    env = dict(os.environ, PATH=f"{bindir}:{os.environ['PATH']}")
    run([sys.executable, a.scons_src.resolve() / "scripts/scons.py", f"-j{a.j}",
         "XGCC_W32_PREFIX=i686-w64-mingw32-", f"SKIPUTILS={SKIPUTILS}", "SKIPDOC=all",
         f"SKIPPLUGINS={SKIPPLUGINS}", f"PREFIX={a.prefix.resolve()}", "VERSION=3.14", "install"],
        cwd=a.nsis_src, env=env, stdout=subprocess.DEVNULL)
    print(f"NSIS installed in {a.prefix}")


if __name__ == "__main__":
    main()
