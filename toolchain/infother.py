"""Driver INFs for Windows' own INF\\OTHER folder.

Windows 98's New Hardware wizard does not search the folders in DevicePath;
it finds a driver by itself only through the INF folder (INF and INF\\OTHER).
An INF there no longer sits beside its driver files, so Windows would ask
for the "KernelExEx drivers" disk. So for each driver INF setup ships, this
makes:
  infother/<name>.inf   the INF without the CopyFiles sections whose files
                        setup ships (sections of Windows' own files, such as
                        usbd.sys or ntmap.sys, stay: those come from the
                        Windows CD as always);
  infother.nsh          macro KexInfOther_<name>: puts those files where the
                        INF would have, and the INF into INF\\OTHER;
                        macro un.KexInfOther_<name>: removes the INF again.
"""
import re
from pathlib import Path

DIRS = {"10": "$WINDIR", "11": "$SYSDIR", "12": "$SYSDIR\\IOSUBSYS", "17": "$WINDIR\\INF", "18": "$WINDIR\\HELP"}


def sections(text):
    out, name = {}, None
    for line in text.splitlines():
        m = re.match(r"\s*\[([^\]]+)\]", line)
        if m:
            name = m.group(1).strip().lower()
            out.setdefault(name, [])
            continue
        if name is not None:
            out[name].append(line)
    return out


def entries(lines):
    for line in lines:
        line = line.split(";", 1)[0].strip()
        if line:
            yield line


def dest_dir(spec):
    parts = [p.strip() for p in spec.split(",")]
    base = DIRS.get(parts[0])
    if base is None:
        raise ValueError(f"unknown destination directory {spec!r}")
    return base + ("\\" + parts[1] if len(parts) > 1 and parts[1] else "")


def find(folder: Path, name: str):
    """a shipped file beside the INF or in a folder under it (any case)"""
    for f in folder.rglob("*"):
        if f.is_file() and f.name.lower() == name.lower():
            return f
    return None


def process(inf: Path, stage: Path, out_dir: Path):
    """returns (macro name, nsis lines, uninstall lines)"""
    text = inf.read_text(encoding="latin-1")
    secs = sections(text)
    dests = {}
    for e in entries(secs.get("destinationdirs", [])):
        k, v = e.split("=", 1)
        dests[k.strip().lower()] = v.strip()
    ours = {}   # copy section -> [(file, dest)]
    names = set()
    for m in re.finditer(r"^\s*CopyFiles\s*=\s*(.+)$", text, re.M | re.I):
        names.update(n.strip() for n in m.group(1).split(";")[0].split(",") if n.strip())
    for n in names:
        if n.startswith("@"):
            continue
        files = [e.split(",")[0].strip() for e in entries(secs.get(n.lower(), []))]
        if files and all(find(inf.parent, f) for f in files):
            d = dests.get(n.lower(), dests.get("defaultdestdir", "11"))
            ours[n.lower()] = [(f, dest_dir(d)) for f in files]

    def strip(m):
        keep = [n.strip() for n in m.group(2).split(",") if n.strip() and n.strip().lower() not in ours]
        return m.group(1) + ",".join(keep) if keep else ""
    new = re.sub(r"^(\s*CopyFiles\s*=\s*)([^;\r\n]*)", strip, text, flags=re.M | re.I)
    base = inf.stem.lower()
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / f"{base}.inf").write_text(new, encoding="latin-1")

    lines, seen = [], set()
    for files in ours.values():
        for f, d in files:
            if (f.lower(), d) in seen:
                continue
            seen.add((f.lower(), d))
            src = find(inf.parent, f).relative_to(stage)
            lines += [f'  CreateDirectory "{d}"', f'  GetTempFileName $0 "{d}"',
                      f'  File /oname=$0 "{str(src).replace("/", chr(92))}"',
                      f'  Delete "{d}\\{f}"', f'  Rename /REBOOTOK $0 "{d}\\{f}"']
    target = f"$WINDIR\\INF\\OTHER\\KernelExEx{base}.inf"
    lines += ['  CreateDirectory "$WINDIR\\INF\\OTHER"', f'  File "/oname={target}" "infother\\{base}.inf"']
    return base, lines, [f'  Delete "{target}"']


def generate(stage: Path, infs):
    nsh = ["; generated by toolchain/infother.py: do not edit", ""]
    for rel in infs:
        base, lines, un = process(stage / rel, stage, stage / "infother")
        nsh += [f"!macro KexInfOther_{base}", *lines, "!macroend", "",
                f"!macro un.KexInfOther_{base}", *un, "!macroend", ""]
    (stage / "infother.nsh").write_text("\n".join(nsh) + "\n", encoding="latin-1")
